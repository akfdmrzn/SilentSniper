using System.Collections.Generic;
using UnityEngine;

namespace SilentContract
{
    [System.Serializable]
    public class AnimEntry
    {
        public string name;      // "walk", "idle_look" ... (without gender prefix)
        public string gender;    // "m" or "f"
        public AnimationClip clip;
        public bool loop;
        public float speed;      // metres per second for locomotion clips (0 for in-place actions)
        public float length;
        public string[] tags;
        public Vector3 offset;   // root displacement over a one-shot clip in the character's frame (x right, z forward)
    }

    /// <summary>All retargeted animation clips (generated by the editor asset pipeline).</summary>
    public class AnimBank : ScriptableObject
    {
        public List<AnimEntry> entries = new List<AnimEntry>();

        Dictionary<string, AnimEntry> map;

        void Build()
        {
            map = new Dictionary<string, AnimEntry>();
            foreach (var e in entries)
                if (e != null && e.clip != null) map[e.gender + "_" + e.name] = e;
        }

        public AnimEntry Get(string gender, string name)
        {
            if (map == null) Build();
            if (map.TryGetValue(gender + "_" + name, out var e)) return e;
            // fall back to the other gender / to plain idle
            if (map.TryGetValue((gender == "f" ? "m" : "f") + "_" + name, out e)) return e;
            return null;
        }

        public bool Has(string gender, string name) => Get(gender, name) != null;
    }
}
